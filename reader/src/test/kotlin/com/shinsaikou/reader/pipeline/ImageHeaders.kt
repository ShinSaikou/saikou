package com.shinsaikou.reader.pipeline

/**
 * Magic-byte headers, one per format, shared by [ImageProbeTest] and
 * [ImageProbeAgreesWithImageUtilTest]. Each is padded to `ImageProbe.HEADER_BYTES` so both
 * sniffers see the same window a real file would give them.
 */
internal object ImageHeaders {

    val JPEG = header(0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46)
    val PNG = header(0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A)
    val GIF87A = header(0x47, 0x49, 0x46, 0x38, 0x37, 0x61)
    val GIF89A = header(0x47, 0x49, 0x46, 0x38, 0x39, 0x61)

    /** RIFF ... WEBP with a plain lossy chunk: static. */
    val WEBP_STATIC = header(
        0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00,
        0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x20,
    )

    /** RIFF ... WEBP with a VP8X chunk whose animation flag, bit 1 of byte 20, is set. */
    val WEBP_ANIMATED = header(
        0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00,
        0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x58,
        0x0A, 0x00, 0x00, 0x00, 0x12, 0x00, 0x00, 0x00,
    )

    /** The same extended chunk with the animation flag clear. */
    val WEBP_EXTENDED_STATIC = header(
        0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00,
        0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x58,
        0x0A, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
    )

    val AVIF = isoBmff("avif")
    val AVIS = isoBmff("avis")
    val HEIC = isoBmff("heic")
    val HEIX = isoBmff("heix")
    val HEVC = isoBmff("hevc")
    val HEVX = isoBmff("hevx")
    val MIF1 = isoBmff("mif1")
    val MSF1 = isoBmff("msf1")
    val MP42 = isoBmff("mp42")

    val JXL_CODESTREAM = header(0xFF, 0x0A)
    val JXL_CONTAINER = header(0x00, 0x00, 0x00, 0x0C, 0x4A, 0x58, 0x4C, 0x20, 0x0D, 0x0A, 0x87, 0x0A)

    val JP2_CONTAINER = header(0x00, 0x00, 0x00, 0x0C, 0x6A, 0x50, 0x20, 0x20, 0x0D, 0x0A, 0x87, 0x0A)
    val JP2_CODESTREAM = header(0xFF, 0x4F, 0xFF, 0x51)

    val GARBAGE = header(0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08)

    fun header(vararg bytes: Int): ByteArray {
        val out = ByteArray(ImageProbe.HEADER_BYTES)
        bytes.forEachIndexed { index, byte -> out[index] = byte.toByte() }
        return out
    }

    private fun isoBmff(brand: String): ByteArray {
        val prefix = listOf(0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70)
        return header(*(prefix + brand.map { it.code }).toIntArray())
    }
}

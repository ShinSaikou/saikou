    @Test
    fun step() {
        val step = arguments.getString(STEP_ARGUMENT)
        if (step.isNullOrBlank()) {
            Log.i(TAG, "Skipped: no sync pair step named")
            return
        }
        // Over Drive, every step's process builds its backend through the fixture's Google endpoints,
        // so the base is required and must be the fixture's before anything builds an endpoint: a
        // step without it would otherwise reach Google's. A WebDAV step leaves the test base alone.
        if (arguments.getString(BACKEND_ARGUMENT) == BACKEND_DRIVE) {
            graph.googleTestBase.value = FixtureGoogleSignIn.fixtureBase(required(GoogleTestBaseSetting.EXTRA_GOOGLE_BASE))
        }
        runBlocking(Dispatchers.IO) {
            val result = linkedMapOf<String, Any?>("step" to step)
            when (step) {
                "seed" -> SyncPairLibrary.seed(graph)
                "sign-in" -> result += signIn()
                "sync" -> result += sync()
                "race-read" -> edit(SyncPairLibrary.RACE_CHAPTER) { ChapterUpdate(id = it, read = true, lastPageRead = RACE_LAST_PAGE) }
                "race-bookmark" -> edit(SyncPairLibrary.RACE_CHAPTER) { ChapterUpdate(id = it, bookmark = true) }
                "race-check" -> raceCheck()
                "rename-chapter" -> edit(SyncPairLibrary.RENAME_CHAPTER) { ChapterUpdate(id = it, name = SyncPairLibrary.RENAMED) }
                "rename-check" -> renameCheck()
                "delete-chapter" -> deleteChapter()
                "delete-read" -> edit(SyncPairLibrary.DELETE_CHAPTER) { ChapterUpdate(id = it, read = true) }
                "delete-check" -> deleteCheck()
                "fresh-categories" -> freshCategories()
                "fresh-check" -> freshCheck()
                "digest" -> Unit
                "bulk-chapters" -> result += "added" to SyncPairLibrary.addBulkChapters(graph)
                "bulk-read" -> result += "marked" to SyncPairLibrary.markBulkRead(graph)
                "kill-in-export" -> killInExport()
                "kill-in-segment" -> killInSegment()
                "after-kill" -> result += afterKill()
                "sync-3000" -> result += sync3000()
                "backlog-add" -> result += SyncPairBacklog.add(graph)
                "backlog-update" -> result += SyncPairBacklog.update(graph)
                "reorder-drag" -> result += SyncPairReorder.drag(graph)
                "reorder-check" -> result += SyncPairReorder.check(graph)
                "tree-nest-reading" -> result += SyncPairTree.nest(graph, SyncPairLibrary.READING, parent = SyncPairLibrary.OLD_NAME)
                "tree-nest-old-name" -> result += SyncPairTree.nest(graph, SyncPairLibrary.OLD_NAME, parent = SyncPairLibrary.READING)
                "tree-delete-old-name" -> result += SyncPairTree.delete(graph, SyncPairLibrary.OLD_NAME)
                "tree-restore" -> result += SyncPairTree.restore(graph, instrumentation.targetContext)
                "tree-check" -> result += SyncPairTree.check(graph)
                "restore-progress" -> result += SyncPairRestore.progress(graph)
                "restore-backup" -> result += SyncPairRestore.restore(graph, instrumentation.targetContext)
                "restore-check" -> result += SyncPairRestore.check(graph)
                "details-edit" -> result += SyncPairEditDetails.edit(graph)
                "details-refresh" -> result += SyncPairEditDetails.refresh(graph)
                "details-reset" -> result += SyncPairEditDetails.reset(graph)
                "details-check" -> result += SyncPairEditDetails.check(graph)
                else -> throw AssertionError("$STEP_ARGUMENT names no step this class knows: $step")
            }
            result += digest()
            flushPreferences()
            report(result)
        }
    }

    /**
     * Every preference the step set, on disk before its process ends. The store writes with `apply()`,
     * which reaches the file up to 100 ms later on API 26 and up, and the instrumentation's process is
     * killed as the step returns: a restore's `restoredSinceSync`, set as the import finishes, was lost
     * that way, so the next step's run never saw the restore (phase 5 unit TG3, item 1's R29).
     * [StagePreferences] since phase 5 unit TG4, which every stage-split class now ends with.
     */
    private fun flushPreferences() = StagePreferences.commit()

    private suspend fun signIn(): Map<String, Any?> = awaitRun(startSignIn())

    /**
     * Everything `sign-in` does before it waits: the periodic run off, the fixture's sign-in stored,
     * and [SyncSession.signedIn], which starts the first run. Returns when it started.
     */
    private suspend fun startSignIn(): Long {
        assertEquals("the device is already signed in", "", SyncPreferences(graph.preferenceStore).backendId.get())
        graph.syncWorkPreferences.intervalHours.set(0)
        graph.syncScheduler.setup()
        val started = now()
        val backend = storeSignIn()
        graph.syncSession.signedIn(backend)
        return started
    }

    /**
     * The fixture's sign-in from the step's arguments, checked and stored; the backend it builds. With
     * [BACKEND_ARGUMENT] `drive`, the fixture's Google sign-in instead ([FixtureGoogleSignIn]).
     */
    private suspend fun storeSignIn(): SyncBackend {
        if (arguments.getString(BACKEND_ARGUMENT) == BACKEND_DRIVE) {
            return FixtureGoogleSignIn.signInBackend(graph)
        }
        val status = graph.webDavAccount.signIn(
            required("saikou.sync.pair.url"),
            required("saikou.sync.pair.user"),
            required("saikou.sync.pair.password"),
        )
        assertTrue("the fixture refused the sign-in: $status", status.reachable && status.authenticated)
        return checkNotNull(graph.webDavAccount.backend()) { "the stored sign-in builds no backend" }
    }

    private suspend fun sync(): Map<String, Any?> {
        awaitNoRun()
        val started = now()
        assertTrue("Sync now enqueued nothing: no backend is configured", graph.syncScheduler.syncNow())
        return awaitRun(started)
    }

    /**
     * Waits until no `sync-once` work is waiting or running and a run has taken the lock since
     * [started], then fails unless that run succeeded. A run WorkManager is backing off to retry
     * ends the wait at once: the step does not wait a minute for a retry, it fails.
     *
     * [orEnded] also accepts a run that took the lock before [started] and succeeded after it:
     * after a kill, WorkManager may resume the killed run itself as the process starts, and Sync
     * now then keeps that run rather than starting another.
     */
    private suspend fun awaitRun(started: Long, orEnded: Boolean = false): Map<String, Any?> {
        val record = graph.syncRunRecord
        val ended = withTimeoutOrNull(RUN_TIMEOUT) {
            while (true) {
                val infos = onceWork()
                if (infos.any { it.state == WorkInfo.State.ENQUEUED && it.runAttemptCount > 0 }) break
                val busy = infos.any {
                    it.state == WorkInfo.State.RUNNING || it.state == WorkInfo.State.ENQUEUED || it.state == WorkInfo.State.BLOCKED
                }
                val ran = record.lastAttemptAt.get() >= started || (orEnded && record.lastSuccessAt.get() >= started)
                if (!busy && ran) break
                delay(POLL_MS)
            }
            true
        }
        // A bare timeout said nothing of which run the step waited for (race step 8 on API 26, once).
        assertTrue("no run since $started ended within $RUN_TIMEOUT: ${runState()}", ended == true)
        val outcome = record.outcome()
        assertTrue("the run failed: $outcome", outcome == SyncOutcome.Success && record.lastSuccessAt.get() >= started)
        val report = record.reports.get().first()
        val preferences = SyncPreferences(graph.preferenceStore)
        return linkedMapOf(
            "outcome" to "success",
            "written" to report.routineMerges + report.conflictCount,
            "conflicts" to report.conflictCount,
            "exported" to report.exported,
            "entriesBefore" to report.before.libraryEntries,
            "entriesAfter" to report.after.libraryEntries,
            "device" to preferences.deviceId.get(),
            "cursors" to preferences.pullCursors.get().size,
            "safetyBackup" to graph.syncWorkPreferences.safetyBackupFile.get().isNotEmpty(),
        )
    }

    private fun onceWork(): List<WorkInfo> = graph.workManager.getWorkInfosForUniqueWork(SyncScheduler.WORK_NAME_ONCE).get()

    /** The run record and every `sync-once` work's state, for a wait that timed out. */
    private fun runState(): String {
        val record = graph.syncRunRecord
        return "last attempt ${record.lastAttemptAt.get()}, last success ${record.lastSuccessAt.get()}, outcome " +
            "${record.outcome()}, sync-once work ${onceWork().map { "${it.state} after ${it.runAttemptCount} attempts" }}"
    }

    /**
     * Waits until no `sync-once` work is queued, blocked or running. Sync now keeps such a run rather
     * than starting another (KEEP), and one the app's start queued, or that began before the step,
     * is not the step's own, so [awaitRun] would never see it. The periodic work is not waited on.
     */
    private suspend fun awaitNoRun() {
        val pending = setOf(WorkInfo.State.ENQUEUED, WorkInfo.State.BLOCKED, WorkInfo.State.RUNNING)
        val idle = withTimeoutOrNull(RUN_TIMEOUT) {
            while (onceWork().any { it.state in pending }) delay(POLL_MS)
            true
        }
        assertTrue("a sync-once run was still queued or running after $RUN_TIMEOUT: ${runState()}", idle == true)
    }

    /** Applies [update] to the scenario entry's live chapter at [url]. */
    private suspend fun edit(url: String, update: (Long) -> ChapterUpdate) {
        val chapter = checkNotNull(SyncPairLibrary.liveChapter(graph, url)) { "no live chapter at $url" }
        graph.chapterRepository.update(update(chapter.id))
    }

    private suspend fun raceCheck() {
        val chapter = checkNotNull(SyncPairLibrary.liveChapter(graph, SyncPairLibrary.RACE_CHAPTER)) { "the race's chapter is gone" }
        assertTrue("the read on one device did not survive: $chapter", chapter.read)
        assertTrue("the bookmark on the other device did not survive: $chapter", chapter.bookmark)
        assertEquals("the last page read is not the higher one", RACE_LAST_PAGE, chapter.lastPageRead)
    }

    private suspend fun renameCheck() {
        val entry = SyncPairLibrary.scenarioEntryId(graph)
        val chapters = graph.chapterRepository.getChapterByMangaId(entry)
        val renamed = chapters.filter { it.url == SyncPairLibrary.RENAME_CHAPTER }
        assertEquals("the renamed chapter is not one row: $renamed", 1, renamed.size)
        assertEquals(SyncPairLibrary.RENAMED, renamed.single().name)
        assertEquals("the entry's chapters were duplicated or lost", SyncPairLibrary.CHAPTERS, chapters.size)
        assertEquals("a second row holds the old name", 0, chapters.count { it.name == "Chapter 7" })
    }

    private suspend fun deleteChapter() {
        val chapter = checkNotNull(SyncPairLibrary.liveChapter(graph, SyncPairLibrary.DELETE_CHAPTER)) { "no live chapter to drop" }
        graph.chapterRepository.removeChaptersWithIds(listOf(chapter.id))
        assertNull(SyncPairLibrary.liveChapter(graph, SyncPairLibrary.DELETE_CHAPTER))
    }

    private suspend fun deleteCheck() {
        assertNull("the dropped chapter is live again", SyncPairLibrary.liveChapter(graph, SyncPairLibrary.DELETE_CHAPTER))
        val entry = SyncPairLibrary.scenarioEntryId(graph)
        assertEquals("the entry lost more than the dropped chapter", SyncPairLibrary.CHAPTERS - 1, graph.chapterRepository.getChapterByMangaId(entry).size)
    }

    private suspend fun freshCategories() {
        val categories = graph.categoryRepository.getAll().associateBy { it.name }
        val old = checkNotNull(categories[SyncPairLibrary.OLD_NAME]) { "no ${SyncPairLibrary.OLD_NAME}" }
        val gone = checkNotNull(categories[SyncPairLibrary.GONE]) { "no ${SyncPairLibrary.GONE}" }
        assertEquals(RenameCategory.Result.Success, graph.renameCategory.await(old.id, SyncPairLibrary.NEW_NAME))
        assertEquals(DeleteCategory.Result.Success, graph.deleteCategory.await(gone.id))
    }

    private suspend fun freshCheck() {
        val live = graph.categoryRepository.getAll()
        val names = live.map { it.name }
        assertTrue("the renamed category did not arrive: $names", SyncPairLibrary.NEW_NAME in names)
        assertTrue("the old name is still a category: $names", SyncPairLibrary.OLD_NAME !in names)
        assertTrue("the deleted category is live: $names", SyncPairLibrary.GONE !in names)
        assertEquals("a category is duplicated: $names", names.size, names.toSet().size)
        val all = graph.database.categoriesQueries.syncGetAll().awaitAsList()
        assertTrue("a category other than the system one has no sync key: $all", all.all { it.sync_key != null })
        assertEquals(
            "the deleted category is not held as deleted",
            1,
            all.count { it.name == SyncPairLibrary.GONE && it.deleted_at != null },
        )
        assertEquals("more than one row holds the renamed category", 1, all.count { it.name == SyncPairLibrary.NEW_NAME })
        for (manga in graph.mangaRepository.getFavorites().filter { it.source == SyncPairLibrary.SOURCE_ID }) {
            val held = graph.categoryRepository.getCategoriesByMangaId(manga.id).map { it.name }
            assertTrue("${manga.url} is in the deleted category: $held", SyncPairLibrary.GONE !in held)
        }
    }

    /**
     * `killed_mid_apply`'s stop inside a full export (R89 carry-over 1, on a device): sign in as
     * `sign-in` does, wait until the pull has committed the first part of the other device's export
     * (its mark in [SyncPreferences.pulledExportParts]), then hold the database's one writer, so no
     * further chunk commits and the mark cannot move, and [awaitKill] with the mark the kill leaves.
     * The pull is then waiting inside the next part.
     */
    private suspend fun killInExport(): Nothing {
        val started = startSignIn()
        val preferences = SyncPreferences(graph.preferenceStore)
        awaitWhileRunning(started, "no part of the other device's export was committed") {
            preferences.pulledExportParts.get().values.any { it.parts >= 1 }
        }
        val held = CountDownLatch(1)
        thread(name = "sync-pair-writer-hold", isDaemon = true) {
            runBlocking { graph.database.transaction { held.countDown(); Thread.sleep(KILL_WAIT_MS * 2) } }
        }
        assertTrue("the database's writer was not free within $HOLD_WAIT_S s", held.await(HOLD_WAIT_S, TimeUnit.SECONDS))
        // A part whose last chunk committed just before the hold writes its mark after the commit.
        Thread.sleep(SETTLE_MS)
        val (device, mark) = checkNotNull(preferences.pulledExportParts.get().entries.singleOrNull()) {
            "the pull finished the export before the hold: marks ${preferences.pulledExportParts.get()}"
        }
        writeKillOutcome(started, "export", JSONObject().put("device", device).put("exportId", mark.exportId).put("mark", mark.parts))
        awaitKill("case=export device=$device export=${mark.exportId} mark=${mark.parts}")
    }

    /**
     * `killed_mid_apply`'s stop inside a segment's transaction: Sync now, then this process's threads
     * are read until one is applying a row ([APPLY_FRAME] on its stack, which only runs inside
     * `SyncStore.apply`'s transaction), and [awaitKill] names that frame.
     */
    private suspend fun killInSegment(): Nothing {
        val started = now()
        writeKillOutcome(started, "segment", JSONObject().put("cursors", JSONObject(SyncPreferences(graph.preferenceStore).pullCursors.get())))
        assertTrue("Sync now enqueued nothing: no backend is configured", graph.syncScheduler.syncNow())
        var frame: String? = null
        awaitWhileRunning(started, "no thread was seen applying a row", pollMs = PROBE_MS) {
            frame = applyFrame()
            frame != null
        }
        awaitKill("case=segment frame=$frame")
    }

    /**
     * Polls [done] until it holds, and fails if the run started at [started] ends first or
     * [RUN_TIMEOUT] passes: either way the moment to stop never came.
     */
    private suspend fun awaitWhileRunning(started: Long, never: String, pollMs: Long = POLL_MS, done: () -> Boolean) {
        val record = graph.syncRunRecord
        val seen = withTimeoutOrNull(RUN_TIMEOUT) {
            while (!done()) {
                if (record.lastSuccessAt.get() >= started) throw AssertionError("$never before the run ended: ${record.outcome()}")
                delay(pollMs)
            }
            true
        }
        assertTrue("$never within $RUN_TIMEOUT", seen == true)
    }

    /** The first stack frame of a thread applying a sync row, as `thread:class.method`, or null. */
    private fun applyFrame(): String? {
        for ((thread, stack) in Thread.getAllStackTraces()) {
            val frame = stack.firstOrNull { it.className.startsWith(APPLY_FRAME) } ?: continue
            return "${thread.name.replace(' ', '_')}:${frame.className}.${frame.methodName}"
        }
        return null
    }

    /**
     * R73's outcome file for the kill, written before the kill so the next process can read it:
     * `schema`, `row` (the scenario), `package`, `pid`, `writtenAt` (the step's start, before any
     * run it stops) and [fields].
     */
    private fun writeKillOutcome(started: Long, case: String, fields: JSONObject) {
        fields.put("schema", ForceStopOutcome.SCHEMA)
            .put("row", KILL_OUTCOME)
            .put("package", instrumentation.targetContext.packageName)
            .put("pid", Process.myPid())
            .put("writtenAt", started)
            .put("case", case)
        ForceStopOutcome.write(KILL_OUTCOME, fields.toString())
    }

    /**
     * Tells the host this process is ready to be stopped, with one `saikou.sync.pair.kill` status line
     * (`pid=<pid>` and [fields]), which `am instrument -r` prints as it arrives, and waits. The host
     * stops the process with `run-as com.shinsaikou kill -9 <pid>` (R89 carry-over 3: `am kill` reads as a
     * force stop on API 36), so this never returns; a host that does not stop it fails the step.
     */
    private fun awaitKill(fields: String): Nothing {
        val line = "pid=${Process.myPid()} $fields"
        Log.i(TAG, "kill $line")
        instrumentation.sendStatus(STATUS_IN_PROGRESS, Bundle().apply { putString(KILL_KEY, line) })
        Thread.sleep(KILL_WAIT_MS)
        throw AssertionError("the host did not stop process ${Process.myPid()} within $KILL_WAIT_MS ms of: $line")
    }

    /**
     * In the process after a kill: the platform's record of how the killed process ended (on API 30
     * and later it must be a signal, 9), then Sync now and the run it starts or keeps, waited for.
     * Reports the runs that finished since the killed step began and what they wrote, which tells a
     * kill inside a transaction (its rows written again after the restart) from one after its commit.
     */
    private suspend fun afterKill(): Map<String, Any?> {
        val outcome = JSONObject(checkNotNull(ForceStopOutcome.read(KILL_OUTCOME)) { "no outcome at ${ForceStopOutcome.path(KILL_OUTCOME)}" })
        val pid = outcome.getInt("pid")
        val killedAfter = outcome.getLong("writtenAt")
        val exit = exitOf(pid)
        val started = now()
        assertTrue("Sync now enqueued nothing: no backend is configured", graph.syncScheduler.syncNow())
        val run = awaitRun(started, orEnded = true)
        // The kill on the wall clock, as the platform recorded the exit (API 30 and later; below,
        // this process's start). A report stamped before it and after the kill step began is the
        // stopped process's own run, which finished before the kill came; one stamped after it is a
        // run since. R29 proof D1 found a single window from the kill step's start counting a run
        // that finished before the kill as written since it.
        val killedAt = exit.at ?: (now() - (SystemClock.elapsedRealtime() - Process.getStartElapsedRealtime()))
        val reports = graph.syncRunRecord.reports.get()
        val before = reports.filter { it.at in killedAfter until killedAt }
        val since = reports.filter { it.at >= killedAt }
        ForceStopOutcome.remove(KILL_OUTCOME)
        return linkedMapOf<String, Any?>(
            "case" to outcome.getString("case"),
            "pid" to pid,
            "exitReason" to exit.reason,
            "exitStatus" to exit.status,
            "runsBeforeKill" to before.size,
            "runsSinceKill" to since.size,
            "writtenSinceKill" to since.sumOf { it.routineMerges + it.conflictCount },
            "marks" to SyncPreferences(graph.preferenceStore).pulledExportParts.get().size,
        ) + run
    }

    /** How a process ended: [reason] and [status], and [at], when it ended, where the platform says. */
    private data class Exit(val reason: String, val status: Int, val at: Long?)

    /**
     * How process [pid] ended, as the platform recorded it: `signaled`, the signal and the time on
     * API 30 and later, where anything else fails; `unknown` below, where there is no record to read.
     */
    private fun exitOf(pid: Int): Exit {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.R) return Exit("unknown", -1, null)
        val context = instrumentation.targetContext
        val exit = context.getSystemService(ActivityManager::class.java)
            .getHistoricalProcessExitReasons(context.packageName, pid, 1).firstOrNull()
        assertTrue("the platform has no record of process $pid ending", exit != null)
        assertEquals("process $pid ended other than by a signal: ${exit!!.description}", ApplicationExitInfo.REASON_SIGNALED, exit.reason)
        assertEquals("process $pid ended by signal ${exit.status}, not 9", 9, exit.status)
        return Exit("signaled", exit.status, exit.timestamp)
    }

    /**
     * `sync_3000_no_oom` (Q11): [SyncLibrarySeeder]'s library at [SYNC_3000_ENTRIES] entries is
     * exported under one device id, then [SYNC_3000_EDITS] more chapters are read here, the device
     * signs out and in again as a new device, and that device's first run (the safety backup, the
     * pull of the first id's export onto the same library with its own edits, which is the owner's
     * case, and its own export) runs on this thread. An [OutOfMemoryError] is counted as
     * `restore_3000_oom_count` counts one, around the call; the used Java heap is sampled every
     * [HEAP_SAMPLE_MS] ms while it runs, with no GC first, so the peak can overstate the live heap
     * (the method note says so; the verdict never reads it). Both runs call [SyncSession.run] directly, with the sign-in stored and no schedule
     * armed, so no WorkManager run can take the lock first. The fragment is published whatever the
     * verdict, and the step fails when it is false.
     */
    private suspend fun sync3000(): Map<String, Any?> {
        val device = required(GateFragments.DEVICE_ARGUMENT)
        val preferences = SyncPreferences(graph.preferenceStore)
        assertEquals("the device is already signed in", "", preferences.backendId.get())
        graph.syncWorkPreferences.intervalHours.set(0)
        graph.syncScheduler.setup()
        SyncLibrarySeeder.seed(graph, SYNC_3000_ENTRIES)

        preferences.backendId.set(storeSignIn().id)
        val first = checkNotNull(graph.syncSession.run()) { "another run held the lock" }
        assertTrue("the first device id did not export the library", first.exported)
        val firstDevice = preferences.deviceId.get()
        val marked = SyncLibrarySeeder.markMoreRead(graph, SYNC_3000_EDITS)
        graph.syncSession.signOut()
        preferences.backendId.set(storeSignIn().id)

        val runtime = Runtime.getRuntime()
        val peak = AtomicLong()
        val sampling = AtomicBoolean(true)
        val sampler = thread(name = "sync-3000-heap", isDaemon = true) {
            while (sampling.get()) {
                peak.accumulateAndGet(runtime.totalMemory() - runtime.freeMemory(), ::maxOf)
                Thread.sleep(HEAP_SAMPLE_MS)
            }
        }
        var outOfMemory = 0
        var failure: String? = null
        var result: SyncRunResult? = null
        val startedAt = SystemClock.elapsedRealtime()
        try {
            result = graph.syncSession.run()
        } catch (error: OutOfMemoryError) {
            outOfMemory = 1
            Log.e(TAG, "the sync of $SYNC_3000_ENTRIES entries ran out of memory", error)
        } catch (error: Exception) {
            failure = error.toString()
        }
        val elapsed = SystemClock.elapsedRealtime() - startedAt
        sampling.set(false)
        sampler.join()

        val problems = buildList {
            if (outOfMemory > 0) add("an OutOfMemoryError")
            failure?.let { add("the run failed: $it") }
            if (failure == null && outOfMemory == 0 && result == null) add("another run held the lock")
            result?.let { run ->
                if (run.after.libraryEntries != SYNC_3000_ENTRIES.toLong()) add("${run.after.libraryEntries} entries after the run")
                if (run.after.readChapters != run.before.readChapters) add("read chapters went from ${run.before.readChapters} to ${run.after.readChapters}")
                if (run.exportsApplied != 1) add("${run.exportsApplied} exports pulled, where the first device id's is one")
            }
            if (firstDevice !in preferences.pullCursors.get()) add("no cursor for the first device id $firstDevice")
            if (preferences.pulledExportParts.get().isNotEmpty()) add("an export mark left behind")
            latched(SyncLibrarySeeder.SOURCE_ID).takeIf { it > 0 }?.let { add("$it rows still latched") }
        }
        val context = instrumentation.targetContext
        val memoryClass = context.getSystemService(ActivityManager::class.java).memoryClass
        val memTotal = MEM_TOTAL.find(GateFragments.shell("cat /proc/meminfo"))?.groupValues?.get(1) ?: "unread"
        val peakMb = peak.get() / MB
        val method = "SyncPairTest step sync-3000 on API ${Build.VERSION.SDK_INT}: SyncLibrarySeeder's $SYNC_3000_ENTRIES entries of " +
            "${SyncLibrarySeeder.CHAPTERS} chapters exported under one device id, $marked more chapters read here, then signed out and " +
            "in again as a new device, whose first run (safety backup, pull of that export, its own export) called SyncSession.run " +
            "directly: OOM count $outOfMemory, peak Java heap $peakMb MB of ${runtime.maxMemory() / MB} MB (used heap sampled every " +
            "$HEAP_SAMPLE_MS ms with no GC first, so garbage not yet collected counts and it can overstate the live peak; the " +
            "verdict does not read it), memoryClass $memoryClass MB, " +
            "MemTotal $memTotal kB, $elapsed ms, ${result?.rowsWritten ?: "no"} rows written, ${result?.conflicts?.size ?: 0} conflicts" +
            (if (problems.isEmpty()) "" else "; failed: ${problems.joinToString("; ")}")
        GateFragments.publish(ROW_3000, device, problems.isEmpty().toString(), "bool", method)
        assertTrue("sync_3000_no_oom is false: ${problems.joinToString("; ")}", problems.isEmpty())
        return linkedMapOf(
            "value" to true,
            "oom" to outOfMemory,
            "peakHeapMb" to peakMb,
            "heapMaxMb" to runtime.maxMemory() / MB,
            "memoryClass" to memoryClass,
            "memTotalKb" to memTotal,
            "ms" to elapsed,
            "written" to result?.rowsWritten,
        )
    }

    /** Rows of the entries under [source] and their chapters whose `is_syncing` is still raised. */
    private suspend fun latched(source: Long): Int {
        val db = graph.database
        var latched = 0
        for (manga in db.mangasQueries.getAllManga().awaitAsList().filter { it.source == source }) {
            if (manga.is_syncing != 0L) latched++
            latched += db.chaptersQueries.syncGetByMangaId(manga._id).awaitAsList().count { it.is_syncing != 0L }
        }
        return latched
    }

    private suspend fun digest(): Map<String, Any?> {
        val digest = SyncPairLibrary.digest(graph)
        return linkedMapOf(
            "digest" to digest.sha256,
            "lines" to digest.lines,
            "latched" to digest.latched,
            "entries" to digest.entries,
            "chapters" to digest.chapters,
            "categories" to digest.categories,
        )
    }

    private fun report(result: Map<String, Any?>) {
        val line = result.entries.joinToString(" ") { (key, value) -> "$key=$value" }
        Log.i(TAG, "result $line")
        instrumentation.sendStatus(STATUS_IN_PROGRESS, Bundle().apply { putString(RESULT_KEY, line) })
    }


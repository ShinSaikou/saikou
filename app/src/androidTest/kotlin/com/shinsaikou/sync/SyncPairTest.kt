/**
 * One step of the two-device suite (phase 3 unit I, Q11), named by `saikou.sync.pair.step`.
 * `tools/bench/sync_pair.py` runs each step with `am instrument` on one of two devices, in the order
 * a scenario gives, so the two devices' steps interleave as two real devices' would. Each step does
 * one thing on its device and returns; the process ends with the instrumentation, and the next step
 * starts it again.
 *
 * With no step named it logs one `Skipped: no sync pair step named` line and returns, strict mode or
 * not, so a suite run passes through it: the step is read directly, as `Args.gatePhase` reads its
 * phase, because absence is an answer here and not a harness error. A step name it does not know
 * fails.
 *
 * The steps:
 * - `seed`: [SyncPairLibrary.seed], on a device the orchestrator has cleared.
 * - `sign-in`: the periodic run off (0 hours, one of the interval setting's values), so no run
 *   starts that a step did not ask for; then [com.shinsaikou.sync.webdav.WebDavAccount.signIn] with
 *   `saikou.sync.pair.url`, `saikou.sync.pair.user` and `saikou.sync.pair.password` (generated by the
 *   orchestrator for its run and never stored in the tree), and [SyncSession.signedIn], which starts
 *   the device's first run at once, as a sign-in in Sync settings does. The step waits for that run,
 *   so no run is left going when the process ends. With `saikou.sync.pair.backend` `drive` (phase 3
 *   unit H, evidence only) it signs in to the fixture's Google Drive instead, through
 *   [FixtureGoogleSignIn]; every step then takes `saikou.google.base`, since each process builds the
 *   Drive backend only while the graph's test base names the fixture.
 * - `sync`: Sync now, and the run it starts, waited for.
 * - `race-read`, `race-bookmark`: the race's two edits of [SyncPairLibrary.RACE_CHAPTER], a read to
 *   the last page on one device and a bookmark on the other; `race-check`: both hold.
 * - `rename-chapter`: [SyncPairLibrary.RENAME_CHAPTER] renamed as a library update renames it;
 *   `rename-check`: one row at that url, renamed, and the entry's chapter count unchanged.
 * - `delete-chapter`: [SyncPairLibrary.DELETE_CHAPTER] dropped as a library update drops it (a hard
 *   delete); `delete-read`: the same chapter read on the other device meanwhile; `delete-check`: the
 *   chapter is not live here.
 * - `fresh-categories`: [SyncPairLibrary.OLD_NAME] renamed to [SyncPairLibrary.NEW_NAME] and
 *   [SyncPairLibrary.GONE] deleted through the app's interactors; `fresh-check`: both arrived renamed
 *   and deleted, no entry is in the deleted one, and no category but the system one has no sync key.
 * - `digest`: the library's digest alone.
 * - `killed_mid_apply`'s steps: `bulk-chapters` ([SyncPairLibrary.addBulkChapters]) and `bulk-read`
 *   ([SyncPairLibrary.markBulkRead]) grow the library into a full export of several parts and a
 *   segment of several thousand rows; `kill-in-export` and `kill-in-segment` stop this process part
 *   way through pulling them and never return (see [awaitKill]); `after-kill`, in the next process,
 *   checks how the killed one ended and syncs again.
 * - `sync-3000`: the `sync_3000_no_oom` row, which this step publishes itself ([sync3000]).
 * - `new_entry_backlog`'s steps (phase 4 unit NB): `backlog-add`, [SyncPairBacklog.add], a library
 *   add of an entry of 100 chapters made as the manga screen makes it; `backlog-update`,
 *   [SyncPairBacklog.update], a manual library update against its source listing one more, with
 *   "Download new chapters" on, reporting what it queued.
 * - `manual_sort_pair`'s steps (phase 4 device coverage unit DC2, item 2): `reorder-drag`,
 *   [SyncPairReorder.drag], one device's reorder of the pair library's `Pair reading` category, the
 *   positions `SetManualLibraryOrder.await` itself would write; `reorder-check`, [SyncPairReorder.check],
 *   the same category's ranked order read back on the other device after both have synced.
 * - the sub-category scenarios' steps (phase 5 unit CT, item 8), through [SyncPairTree]:
 *   `tree-nest-reading` puts [SyncPairLibrary.READING] under [SyncPairLibrary.OLD_NAME] and
 *   `tree-nest-old-name` puts [SyncPairLibrary.OLD_NAME] under [SyncPairLibrary.READING], each as the
 *   Categories screen's "Move under" does; `tree-delete-old-name` deletes [SyncPairLibrary.OLD_NAME]
 *   as the screen does; `tree-restore` restores a backup of the pair library's categories, flat;
 *   `tree-check` reports the tree the screens show and how many categories store a parent.
 * - `restore_then_join`'s steps (phase 5 unit TG3, item 1), through [SyncPairRestore]:
 *   `restore-progress` reads further on some of the pair library's entries; `restore-backup`
 *   restores a backup built from fixture rows of those entries and two more; `restore-check`
 *   asserts every chapter of both is there with both devices' reads, bookmarks and the higher page.
 * - `edit_details_race`'s steps (phase 5 unit ED), through [SyncPairEditDetails]: `details-edit` saves
 *   the owner's title and description for the scenario entry as the Edit details dialog does;
 *   `details-refresh` refreshes the entry from a fixture source whose title changed; `details-reset`
 *   is the dialog's Reset; `details-check` reports what the screens show and the source's text under it.
 *
 * Every step reports through `Instrumentation.sendStatus` (code [STATUS_IN_PROGRESS], which the
 * runner's parsers read as progress, never as a test result) one `saikou.sync.pair.result` line of
 * `key=value` pairs: the step's name, the library's [SyncPairLibrary.Digest] as the step left it,
 * and for `sign-in` and `sync` the run's outcome and report. The orchestrator reads it from the raw
 * `am instrument -r` output and compares the two devices. The line is logged under [TAG] too.
 */
@RunWith(AndroidJUnit4::class)
